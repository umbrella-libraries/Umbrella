	[Fact]
	public async Task PublicVirtualMethodWithChangeableSignature_ShouldTriggerDiagnostic()
	{
		const string source = "using System.Threading.Tasks; public class TestClass { public virtual async Task RunAsync() { await Task.Yield(); } }";

		await VerifyAnalyzerAsync(source, ExpectedAt(source, "RunAsync"));
	}

	[Fact]
	public async Task UserDefinedTaskType_ShouldNotTriggerDiagnostic()
	{
		const string source = "public class Task { } public class TestClass { public async Task RunAsync() { await System.Threading.Tasks.Task.Yield(); } }";

		await VerifyNoDiagnosticsAsync(source);
	}

	private static ExpectedDiagnostic ExpectedAt(string source, string methodName)
	{
		int column = source.IndexOf(methodName + "(", StringComparison.Ordinal) + 1;
		return Diagnostic(AsyncMethodCancellationAnalyzer.Rule, 1, column, methodName);
	}
}
